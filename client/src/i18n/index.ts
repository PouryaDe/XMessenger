const rawSavedLang = typeof window !== 'undefined' ? localStorage.getItem('xmessenger_lang') : null;
const savedLang = rawSavedLang === 'en' ? 'en' : 'fa';
if (typeof window !== 'undefined' && !rawSavedLang) {
  localStorage.setItem('xmessenger_lang', 'fa');
}

i18n
  .use(initReactI18next)
  .init({
    resources,
    lng: savedLang,
    fallbackLng: 'fa',
    interpolation: {
      escapeValue: false
    }
  });

// Automatically update HTML dir and lang attributes
export function setAppLanguage(lang: 'fa' | 'en') {
  i18n.changeLanguage(lang);
  localStorage.setItem('xmessenger_lang', lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'fa' ? 'rtl' : 'ltr';
}

// Initial set
document.documentElement.lang = savedLang;
document.documentElement.dir = savedLang === 'fa' ? 'rtl' : 'ltr';

export default i18n;
